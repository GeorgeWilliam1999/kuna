#!/bin/sh
# kuna — host-side helper for the Kuna agent environment.
#
# Installed to ~/.kuna/bin/kuna by the Kuna app (locally and on every SSH host
# you use). It is plain POSIX sh so it runs on old cluster login nodes too.
# Everything lives under ~/.kuna; deleting that directory removes all traces
# (running agents keep running in the `tmux -L kuna` server).
#
# All arguments that may contain arbitrary text are passed base64-encoded so
# the command line survives any remote login shell (bash, zsh, tcsh, ...).

KUNA_VERSION=__KUNA_VERSION__
K="$HOME/.kuna"
A="$K/agents"
CONF="$K/tmux.conf"
T=$(cat "$K/tmux-path" 2>/dev/null)
[ -n "$T" ] && [ -x "$T" ] || T=tmux

SOCK=${KUNA_TMUX_SOCKET:-kuna} # tests use their own tmux server
CDIR=${CLAUDE_CONFIG_DIR:-$HOME/.claude}

tm() { "$T" -L "$SOCK" -f "$CONF" "$@"; }

# Agent ids (Kuna's hex ids, background sessions' short ids) end up in paths
# that get removed, tmux targets and claude arguments: nothing else gets through.
valid_id() {
  case "$1" in ''|*[!A-Za-z0-9_-]*) echo "kuna: invalid id: $1" >&2; exit 2 ;; esac
}

valid_num() {
  for n in "$@"; do
    case "$n" in ''|*[!0-9]*) echo "kuna: not a number: $n" >&2; exit 2 ;; esac
  done
}

b64d() {
  if [ -z "$1" ]; then return 0; fi
  printf '%s' "$1" | base64 -d 2>/dev/null || printf '%s' "$1" | base64 -D
}

expand() {
  case "$1" in
    "~") printf '%s' "$HOME" ;;
    "~/"*) printf '%s/%s' "$HOME" "${1#\~/}" ;;
    *) printf '%s' "$1" ;;
  esac
}

fstat() {
  # prints "<mtime>\t<size>" for a file; GNU stat first, BSD stat second
  stat -c '%Y	%s' "$1" 2>/dev/null || stat -f '%m	%z' "$1" 2>/dev/null
}

# --------------------------------------------------------------- setup ----

discover() {
  # Ask the user's login shell where tmux and claude live, so modules,
  # conda and ~/.local/bin are all honoured. Guard against shells that hang.
  out="$K/.discover.$$"
  sh_=${SHELL:-/bin/sh}
  case "$sh_" in
    *csh) "$sh_" -c 'echo "@@tmux `which tmux`"; echo "@@claude `which claude`"' </dev/null >"$out" 2>/dev/null & ;;
    *) "$sh_" -lic 'printf "@@tmux %s\n@@claude %s\n" "$(command -v tmux)" "$(command -v claude)"' </dev/null >"$out" 2>/dev/null & ;;
  esac
  pid=$!
  ( sleep 20; kill "$pid" 2>/dev/null ) >/dev/null 2>&1 &
  killer=$!
  wait "$pid" 2>/dev/null
  kill "$killer" 2>/dev/null
  tpath=$(sed -n 's/^@@tmux \(\/.*\)$/\1/p' "$out" | head -n 1)
  cpath=$(sed -n 's/^@@claude \(\/.*\)$/\1/p' "$out" | head -n 1)
  rm -f "$out"
  [ -n "$tpath" ] || tpath=$(command -v tmux 2>/dev/null)
  [ -n "$tpath" ] && printf '%s' "$tpath" > "$K/tmux-path"
  [ -n "$cpath" ] && printf '%s' "$cpath" > "$K/claude-path"
}

write_conf() {
  term=screen-256color
  infocmp tmux-256color >/dev/null 2>&1 && term=tmux-256color
  cat > "$CONF" <<EOF
# Kuna's private tmux server config (tmux -L kuna). Regenerated by the app.
set -g prefix None
unbind-key -a
set -g status off
set -g escape-time 0
set -g history-limit 100000
set -g remain-on-exit on
set -g mouse on
set -g focus-events on
set -g set-titles off
set -g allow-rename off
set -g mode-keys vi
set -g default-terminal "$term"
set -ga terminal-overrides ",xterm-256color:Tc"
set -ga terminal-overrides ',xterm-256color:Ms=\\E]52;%p1%s;%p2%s\\007'
set -g set-clipboard on
setw -g aggressive-resize on
EOF
  # newer tmux only; ignore failures on old versions
  if "$T" -V 2>/dev/null | grep -Eq 'tmux (3\.[2-9]|[4-9])'; then
    printf 'set -g window-size latest\nset -g extended-keys on\nset -as terminal-features ",xterm-256color:RGB:extkeys:clipboard"\n' >> "$CONF"
  fi
  if "$T" -V 2>/dev/null | grep -Eq 'tmux (3\.[3-9]|[4-9])'; then
    # hide tmux's own "Pane is dead" line; kuna prints its own exit note
    printf "set -g remain-on-exit-format ' '\n" >> "$CONF"
  fi
}

write_hooks() {
  h="sh '$K/bin/kuna' hook"
  ev=""
  for e in SessionStart UserPromptSubmit PreToolUse PostToolUse Notification PermissionRequest Stop SubagentStop PreCompact SessionEnd; do
    [ -n "$ev" ] && ev="$ev,"
    ev="$ev\"$e\":[{\"hooks\":[{\"type\":\"command\",\"command\":\"$h\",\"timeout\":5}]}]"
  done
  # the status line command receives rate_limits (plan usage) from Claude Code
  printf '{"hooks":{%s},"statusLine":{"type":"command","command":"sh %s statusline"}}\n' "$ev" "'$K/bin/kuna'" > "$K/claude-hooks.json"
}

setup() {
  mkdir -p "$K/bin" "$A"
  # prompts, commands and status in here are nobody else's business on a shared
  # node; the directory, not the files' modes, keeps others out (agents keep the
  # user's own umask for what they write)
  chmod 700 "$K" 2>/dev/null
  discover 2>/dev/null
  T=$(cat "$K/tmux-path" 2>/dev/null)
  [ -n "$T" ] || T=tmux
  write_conf
  write_hooks
  # context sizes of transcripts nobody touched for a month (recomputed if needed)
  [ -d "$K/ctx" ] && find "$K/ctx" -type f -mtime +30 -exec rm -f {} + 2>/dev/null
  printf '%s' "$KUNA_VERSION" > "$K/version"
  doctor
}

doctor() {
  printf 'version\t%s\n' "$KUNA_VERSION"
  printf 'home\t%s\n' "$HOME"
  printf 'os\t%s\n' "$(uname -sm 2>/dev/null)"
  printf 'hostname\t%s\n' "$(hostname 2>/dev/null)"
  printf 'tmux\t%s\n' "$(cat "$K/tmux-path" 2>/dev/null)"
  printf 'tmuxv\t%s\n' "$("$T" -V 2>/dev/null)"
  printf 'claude\t%s\n' "$(cat "$K/claude-path" 2>/dev/null)"
}

# -------------------------------------------------------------- agents ----

spawn() {
  # spawn <id> <cwd64> <cmd64> <cols> <rows> <meta64> <prompt64>
  valid_id "$1"
  valid_num "$4" "$5"
  id=$1
  cwd=$(expand "$(b64d "$2")")
  d="$A/$id"
  if [ ! -d "$cwd" ]; then echo "kuna: directory does not exist: $cwd" >&2; exit 3; fi
  mkdir -p "$d"
  b64d "$3" > "$d/cmd"
  b64d "$6" > "$d/meta.json"
  b64d "$7" > "$d/prompt"
  date +%s > "$d/attn.base"
  tm new-session -d -s "kuna_$id" -x "$4" -y "$5" -c "$cwd" "sh '$K/bin/kuna' run $id" || exit 4
  echo "ok"
}

run() {
  # Runs inside the tmux pane: start the agent through the user's login shell.
  valid_id "$1"
  d="$A/$1"
  KUNA_AGENT_ID=$1
  KUNA_DIR=$d
  COLORTERM=truecolor
  # an interactive login shell may stop at oh-my-zsh's update question
  DISABLE_AUTO_UPDATE=true
  DISABLE_UPDATE_PROMPT=true
  export KUNA_AGENT_ID KUNA_DIR COLORTERM DISABLE_AUTO_UPDATE DISABLE_UPDATE_PROMPT
  cmd=$(cat "$d/cmd")
  sh_=${SHELL:-/bin/sh}
  case "$sh_" in
    *csh) "$sh_" -c "$cmd" ;;
    *) "$sh_" -lic "$cmd" ;;
  esac
  code=$?
  printf '%s' "$code" > "$d/exit"
  printf '%s' "$(date +%s)" > "$d/attn"
  printf '\n\033[2m[kuna] agent exited with code %s — the session stays open until you kill it]\033[0m\n' "$code"
}

kill_agent() {
  valid_id "$1"
  tm kill-session -t "kuna_$1" 2>/dev/null
  rm -rf "${A:?}/$1"
  echo "ok"
}

key() {
  # key <id> <tmux-key-name...>
  valid_id "$1"
  id=$1; shift
  tm send-keys -t "kuna_$id" "$@"
}

send() {
  # send <id> <text64>: replace whatever is in the agent's input box with text
  # and press Enter. End, then Ctrl+U/Backspace empties a draft of up to six
  # lines (Ctrl+Y in Claude Code brings it back). Enter goes on its own, so
  # Claude Code doesn't take it as part of a paste.
  valid_id "$1"
  id=$1
  tm send-keys -t "kuna_$id" C-e C-u BSpace C-u BSpace C-u BSpace C-u BSpace C-u BSpace C-u BSpace &&
    tm send-keys -t "kuna_$id" -l -- "$(b64d "$2")" || return 1
  sleep 0.3 2>/dev/null || sleep 1
  tm send-keys -t "kuna_$id" Enter
}

attach() {
  valid_id "$1"
  if ! tm has-session -t "kuna_$1" 2>/dev/null; then
    printf '\033[2m[kuna] agent %s is not running on %s\033[0m\n' "$1" "$(hostname)"
    exit 1
  fi
  exec "$T" -u -L "$SOCK" -f "$CONF" attach-session -t "kuna_$1"
}

# ----------------------------------------------- claude background sessions ----
# Sessions started with `claude --bg` or from `claude agents` live in Claude
# Code's own daemon. Kuna lists them from ~/.claude/jobs/*/state.json, attaches
# with `claude attach`, and stops/removes/respawns them with the claude CLI.

claude_bin() {
  c=$(cat "$K/claude-path" 2>/dev/null)
  [ -n "$c" ] && [ -x "$c" ] && { printf '%s' "$c"; return; }
  printf 'claude'
}

login_run() {
  # run a command line through the user's login shell (PATH, modules, conda)
  sh_=${SHELL:-/bin/sh}
  DISABLE_AUTO_UPDATE=true
  DISABLE_UPDATE_PROMPT=true
  export DISABLE_AUTO_UPDATE DISABLE_UPDATE_PROMPT
  case "$sh_" in
    *csh) "$sh_" -c "$1" ;;
    *) "$sh_" -lic "$1" ;;
  esac
}

bgspawn() {
  # bgspawn <cwd64> <cmd64> <prompt64>: start `claude --bg …` in cwd, print its id
  cwd=$(expand "$(b64d "$1")")
  if [ ! -d "$cwd" ]; then echo "kuna: directory does not exist: $cwd" >&2; exit 3; fi
  mkdir -p "$K/tmp"
  KUNA_PROMPT_FILE="$K/tmp/prompt.$$"
  export KUNA_PROMPT_FILE
  b64d "$3" > "$KUNA_PROMPT_FILE"
  cd "$cwd" || exit 3
  out=$(login_run "$(b64d "$2")" < /dev/null 2>&1)
  rm -f "$KUNA_PROMPT_FILE"
  id=$(printf '%s\n' "$out" | sed -n 's/.*claude attach \([0-9a-f]\{8\}\).*/\1/p' | head -n 1)
  if [ -z "$id" ]; then printf '%s\n' "$out" | grep -v -i 'job control\|terminal process group\|no job control' | tail -n 5 >&2; exit 4; fi
  echo "$id"
}

cc() {
  # cc <stop|rm|respawn|logs> <id>: claude CLI subcommands for background sessions
  case "$1" in stop|rm|respawn|logs) ;; *) echo "kuna: unsupported: $1" >&2; exit 2 ;; esac
  valid_id "$2"
  "$(claude_bin)" "$1" "$2" < /dev/null 2>&1
}

cattach() {
  # attach this terminal to a background session (revives a stopped one)
  valid_id "$1"
  exec "$(claude_bin)" attach "$1"
}

bg_snapshot() {
  # One J line per background session (+ Q with its open question, S with its
  # transcript size). Liveness: a worker in the daemon roster whose pid exists.
  [ -d "$CDIR/jobs" ] || return 0
  live=""
  for w in $(tr -d ' \n\t' 2>/dev/null < "$CDIR/daemon/roster.json" | grep -o '"[0-9a-f]\{8\}":{"pid":[0-9]*' | sed 's/"\([0-9a-f]*\)":{"pid":\([0-9]*\)/\1:\2/'); do
    kill -0 "${w#*:}" 2>/dev/null && live="$live ${w%%:*}"
  done
  set -- "$CDIR"/jobs/*/state.json
  [ -f "$1" ] || return 0
  mkdir -p "$K/ctx"
  awk -v live="$live" '
    function flush() {
      if (file == "") return
      id = file; sub(/\/state\.json$/, "", id); sub(/.*\//, "", id)
      alive = index(" " live " ", " " id " ") ? 1 : 0
      tp = jstr("linkScanPath")
      # J id alive state tempo updatedAt createdAt tokens sessionId cwd worktree transcript name detail needs lastReply modelFlag
      printf "J\t%s\t%d\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n", id, alive, jstr("state"), jstr("tempo"), jstr("updatedAt"), jstr("createdAt"), jstr("tokens"), jstr("sessionId"), jstr("cwd"), jstr("worktreePath"), tp, substr(jstr("name"), 1, 200), substr(jstr("detail"), 1, 300), substr(jstr("needs"), 1, 400), substr(jstr("result"), 1, 400), mflag()
      b = jobj("block")
      if (b != "") printf "Q\t%s\t%s\n", id, b
      f = jobj("inFlight")
      if (f != "") printf "F\t%s\t%s\n", id, f
      if (tp != "") paths = paths tp "\n"
      else if (jstr("sessionId") != "") paths = paths "?" jstr("sessionId") "\n"
    }
    function jstr(key,   i, rest, out, k, c, esc) {
      i = index(buf, "\"" key "\"")
      if (!i) return ""
      rest = substr(buf, i + length(key) + 2)
      sub(/^[ ]*:[ ]*/, "", rest)
      if (substr(rest, 1, 1) != "\"") { if (match(rest, /^[-0-9.a-z]+/)) return substr(rest, 1, RLENGTH); return "" }
      out = ""; esc = 0
      for (k = 2; k <= length(rest) && length(out) < 600; k++) {
        c = substr(rest, k, 1)
        if (esc) { out = out ((c == "n" || c == "t" || c == "r") ? " " : c); esc = 0; continue }
        if (c == "\\") { esc = 1; continue }
        if (c == "\"") break
        out = out c
      }
      gsub(/\t/, " ", out)
      return out
    }
    function mflag(   i, rest) {
      # the --model it was started with, from "respawnFlags": [..., "--model", "sonnet[1m]", ...]
      i = index(buf, "\"respawnFlags\"")
      if (!i) return ""
      rest = substr(buf, i + 14)
      if (match(rest, /[]][ ]*[,}]/)) rest = substr(rest, 1, RSTART)
      if (match(rest, /"--model"[ ]*,[ ]*"[^"]*"/)) {
        rest = substr(rest, RSTART, RLENGTH)
        sub(/^"--model"[ ]*,[ ]*"/, "", rest)
        return substr(rest, 1, length(rest) - 1)
      }
      if (match(rest, /"--model=[^"]*"/)) return substr(rest, RSTART + 9, RLENGTH - 10)
      return ""
    }
    function jobj(key,   i, rest, j, d, k, c) {
      i = index(buf, "\"" key "\"")
      if (!i) return ""
      rest = substr(buf, i + length(key) + 2)
      sub(/^[ ]*:[ ]*/, "", rest)
      if (substr(rest, 1, 1) != "{") return ""
      d = 0
      for (k = 1; k <= length(rest); k++) {
        c = substr(rest, k, 1)
        if (c == "{") d++
        else if (c == "}") { d--; if (d == 0) return substr(rest, 1, k) }
      }
      return ""
    }
    FNR == 1 { flush(); file = FILENAME; buf = "" }
    { gsub(/\t/, " "); buf = buf $0 " " }
    END { flush(); printf "%s", paths > "/dev/stderr" }
  ' "$@" 2> "$K/.bgpaths.$$"
  # transcript sizes in one go (S size path), plus how full each context is
  # (C tokens peak model path) and the tool it is in the middle of (T tool
  # summary path), worked out from the end of a transcript when it grew, at
  # most every 10 s, and cached in ~/.kuna/ctx as
  # "size tokens peak model time tool summary" ("-": not known / none)
  set --
  while IFS= read -r tp; do
    case "$tp" in
      '?'*) for tp in "$CDIR"/projects/*/"${tp#?}".jsonl; do break; done ;; # not linked yet: find by session id
    esac
    [ -n "$tp" ] && [ -f "$tp" ] && set -- "$@" "$tp"
  done < "$K/.bgpaths.$$"
  rm -f "$K/.bgpaths.$$"
  [ $# -gt 0 ] || return 0
  now=$(date +%s)
  wc -c "$@" 2>/dev/null | while read -r sz tp; do
    case "$tp" in /*) ;; *) continue ;; esac # skip wc's "total"
    printf 'S\t%s\t%s\n' "$sz" "$tp"
    c="$K/ctx/${tp##*/}"
    csz=""; cx=""; cpk=""; cm=""; cts=""; ctool=""; csum=""
    [ -f "$c" ] && IFS='	' read -r csz cx cpk cm cts ctool csum < "$c"
    case "$cx" in -|[0-9]*) ;; *) csz="" ;; esac
    case "$cpk$cts" in ''|*[!0-9]*) csz="" ;; esac
    [ -n "$csz" ] || { cx=-; cpk=0; cm=-; cts=0; }
    [ -n "$ctool" ] || ctool=-
    [ -n "$csum" ] || csum=-
    if [ "$csz" != "$sz" ] && [ $((now - cts)) -ge 10 ]; then
      r=$(tail -c 262144 "$tp" | context_tail)
      if [ -n "$r" ]; then
        IFS='	' read -r rx rpk rm rtool rsum <<EOF
$r
EOF
        [ "$rx" != "-" ] && cx=$rx
        [ "$rpk" -gt "$cpk" ] && cpk=$rpk
        [ "$rm" != "-" ] && cm=$rm
        ctool=$rtool
        csum=$rsum
      fi
      printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$sz" "$cx" "$cpk" "$cm" "$now" "$ctool" "$csum" > "$c"
    fi
    [ "$ctool" != "-" ] && printf 'T\t%s\t%s\t%s\n' "$ctool" "$csum" "$tp"
    [ "$cx" = "-" ] && continue
    [ "$cpk" -lt "$cx" ] && cpk=$cx
    printf 'C\t%s\t%s\t%s\t%s\n' "$cx" "$cpk" "$cm" "$tp"
  done
}

context_tail() {
  # stdin: the end of a transcript. Prints "tokens<TAB>peak<TAB>model<TAB>tool<TAB>summary":
  # the last main-thread reply's input + cache tokens (or what a compaction
  # left), the most seen, its model, and the tool call still waiting for its
  # result, if any ("-" for what is not known).
  awk '
    function num(s, k,   i, r) {
      i = index(s, "\"" k "\":")
      if (!i) return 0
      r = substr(s, i + length(k) + 3)
      return match(r, /^[0-9]+/) ? substr(r, 1, RLENGTH) + 0 : 0
    }
    function str(s, k,   i, r) {
      i = index(s, "\"" k "\":\"")
      if (!i) return ""
      r = substr(s, i + length(k) + 4)
      return match(r, /^[^"<]+/) ? substr(r, 1, RLENGTH) : ""
    }
    function model_of(s,   c, k, m, r) {
      # the "model" of the reply itself, not one in a tool call inside its
      # content: the first one if it comes before the content, otherwise the
      # last one that names a Claude model
      s = substr(s, index(s, "\"message\":{"))
      c = index(s, "\"content\":")
      k = index(s, "\"model\":\"")
      if (k && (!c || k < c)) return str(s, "model")
      r = ""
      while ((k = index(s, "\"model\":\"")) > 0) {
        m = str(s, "model")
        if (index(m, "claude")) r = m
        s = substr(s, k + 9)
      }
      return r
    }
    # subagent progress records carry the replies of the subagent nested inside
    /"type":"progress"/ { next }
    /"type":"assistant"/ && !/"isSidechain":true/ && index($0, "\"usage\":{") {
      u = substr($0, index($0, "\"usage\":{"))
      n = num(u, "input_tokens") + num(u, "cache_creation_input_tokens") + num(u, "cache_read_input_tokens")
      if (n > 0) { ctx = n; found = 1; if (n > peak) peak = n }
      m = model_of($0)
      if (m != "") model = m
    }
    /"subtype":"compact_boundary"/ {
      m = substr($0, index($0, "\"compactMetadata\""))
      ctx = num(m, "postTokens"); found = 1
      if (num(m, "preTokens") > peak) peak = num(m, "preTokens")
    }
    # the last tool call of the main thread, until its result comes back
    /"type":"assistant"/ && !/"isSidechain":true/ && index($0, "\"type\":\"tool_use\"") {
      s = $0
      while ((i = index(s, "\"type\":\"tool_use\"")) > 0) {
        s = substr(s, i + 17)
        j = index(s, "\"type\":\"tool_use\"")
        seg = j ? substr(s, 1, j) : s
        tid = str(seg, "id")
        if (tid == "") continue
        pid = tid
        pname = str(seg, "name")
        psum = str(seg, "command")
        if (psum == "") psum = str(seg, "file_path")
        if (psum == "") psum = str(seg, "description")
        if (psum == "") psum = str(seg, "pattern")
      }
    }
    /"type":"user"/ && pid != "" && index($0, "\"tool_use_id\":\"" pid "\"") { pid = ""; pname = ""; psum = "" }
    END {
      if (!found && pname == "") exit
      gsub(/[\t\\]/, " ", psum)
      printf "%s\t%d\t%s\t%s\t%s\n", (found ? ctx + 0 : "-"), peak + 0, (model == "" ? "-" : model), (pname == "" ? "-" : pname), (psum == "" ? "-" : substr(psum, 1, 120))
    }
  '
}

# --------------------------------------------------------------- hooks ----

hook() {
  # Claude Code hook entry point. Must stay silent on stdout.
  p=$(cat)
  [ -n "$KUNA_AGENT_ID" ] || exit 0
  d="$A/$KUNA_AGENT_ID"
  [ -d "$d" ] || exit 0
  p=$(printf '%s' "$p" | head -c 8000 | tr '\n\t' '  ')
  ev=$(field hook_event_name)
  tool=$(field tool_name)
  nt=$(field notification_type)
  pm=$(field permission_mode)
  tp=$(field transcript_path)
  msg=$(field message | cut -c1-200)
  now=$(date +%s)
  [ -n "$tp" ] && printf '%s' "$tp" > "$d/transcript"
  printf '%s\t%s\t%s\t%s\t%s\t%s' "$now" "$ev" "$tool" "$nt" "$pm" "$msg" > "$d/status.tmp" && mv -f "$d/status.tmp" "$d/status"
  case "$ev" in
    Stop|PermissionRequest|SessionEnd) printf '%s' "$now" > "$d/attn" ;;
    Notification)
      case "$nt$msg" in
        *idle*|*"waiting for your input"*) ;;
        *) printf '%s' "$now" > "$d/attn" ;;
      esac ;;
  esac
  exit 0
}

statusline() {
  # Claude Code status line entry point: keep the latest plan usage
  # ("rate_limits": five_hour / seven_day, used_percentage + resets_at) in
  # ~/.kuna/usage for the watch stream. Prints nothing, so the line stays empty.
  p=$(cat)
  case "$p" in *'"rate_limits"'*) ;; *) exit 0 ;; esac
  rl=$(printf '%s' "$p" | tr -d '\n' | awk '{
    i = index($0, "\"rate_limits\"")
    if (!i) exit
    s = substr($0, i)
    j = index(s, "{")
    if (!j) exit
    d = 0
    for (k = j; k <= length(s); k++) {
      c = substr(s, k, 1)
      if (c == "{") d++
      else if (c == "}") { d--; if (d == 0) { print substr(s, j, k - j + 1); exit } }
    }
  }')
  [ -n "$rl" ] || exit 0
  old=$(cut -f2- "$K/usage" 2>/dev/null)
  [ "$old" = "$rl" ] && exit 0
  printf '%s\t%s' "$(date +%s)" "$rl" > "$K/usage.tmp.$$" && mv -f "$K/usage.tmp.$$" "$K/usage"
  exit 0
}

field() {
  printf '%s' "$p" | sed -n "s/.*\"$1\" *: *\"\\([^\"]*\\)\".*/\\1/p" | head -n 1
}

# --------------------------------------------------------------- watch ----

snapshot() {
  tm list-panes -a -F '#{session_name}	#{pane_dead}	#{session_activity}	#{session_created}	#{session_attached}	#{pane_current_command}	#{pane_in_mode}	#{pane_title}' 2>/dev/null |
  while IFS= read -r line; do
    s=${line%%	*}
    case "$s" in kuna_*) ;; *) continue ;; esac
    # Look at the bottom of the screen: 2 = a question/menu is waiting for a
    # choice, 1 = Claude Code's spinner ("✳ Blanching… (7s · ↓ 1.2k tokens)",
    # older versions: "esc to interrupt"), 0 = neither.
    scr=$(tm capture-pane -p -t "$s" 2>/dev/null | grep -v '^[[:space:]]*$' | tail -n 12)
    busy=0
    if printf '%s\n' "$scr" | grep -qE 'Enter to confirm|Esc to cancel|Do you want to'; then busy=2
    elif printf '%s\n' "$scr" | grep -qE '… *\([0-9]|to interrupt'; then busy=1
    fi
    printf 'P\t%s\t%s\n' "$busy" "$line"
  done
  # plan usage reported by any agent's status line on this host
  [ -f "$K/usage" ] && printf 'U\t%s\n' "$(cat "$K/usage")"
  for d in "$A"/*; do
    [ -d "$d" ] || continue
    id=${d##*/}
    tp=$(cat "$d/transcript" 2>/dev/null)
    sz=0
    [ -n "$tp" ] && [ -f "$tp" ] && sz=$(wc -c < "$tp" | tr -d ' ')
    printf 'A\t%s\t%s\t%s\t%s\t%s\t%s\n' "$id" "$(cat "$d/attn" 2>/dev/null)" "$sz" "$(cat "$d/exit" 2>/dev/null)" "$tp" "$(cat "$d/status" 2>/dev/null)"
    printf 'M\t%s\t%s\n' "$id" "$(tr -d '\n' < "$d/meta.json" 2>/dev/null)"
  done
}

watch() {
  # Kept light on purpose: these run on shared login nodes. A tick every 2 s
  # while something changes, every 5 s once quiet for ~30 s; Claude background
  # sessions are re-read only when their state or the roster changed, when a
  # transcript grew (checked every ~10 s) or every ~30 s, and a heartbeat goes
  # out at least every 30 s so a dead connection is noticed.
  prev=""
  quiet=0
  since=0
  bgsig=""
  tsig=""
  bgtsig=""
  bgout=""
  bgage=0
  tps=""
  while :; do
    sig=$(ls -l "$CDIR"/jobs/*/state.json "$CDIR/daemon/roster.json" 2>/dev/null | cksum)
    # grown transcripts (context sizes) count too, looked at every ~10 s;
    # their paths are Claude's sanitized names: safe to word-split
    [ -n "$tps" ] && [ "$bgage" -ge 10 ] && tsig=$(ls -l $tps 2>/dev/null | cksum)
    if [ "$sig" != "$bgsig" ] || [ "$tsig" != "$bgtsig" ] || [ "$bgage" -ge 30 ]; then
      bgout=$(bg_snapshot)
      tps=$(printf '%s\n' "$bgout" | sed -n 's/^S	[0-9]*	//p')
      bgsig=$sig
      bgtsig=$tsig
      bgage=0
    fi
    cur=$(snapshot; [ -n "$bgout" ] && printf '%s\n' "$bgout")
    if [ "$cur" != "$prev" ] || [ "$since" -ge 30 ]; then
      # printing also detects a dead connection: the write fails and we exit
      printf '%s\n@@END\t%s\n' "$cur" "$(date +%s)" || exit 0
      [ "$cur" != "$prev" ] && quiet=0
      prev=$cur
      since=0
    else
      quiet=$((quiet + 1))
    fi
    if [ "$quiet" -ge 15 ]; then step=5; else step=2; fi
    sleep "$step"
    since=$((since + step))
    bgage=$((bgage + step))
  done
}

# --------------------------------------------------------------- files ----

read_bytes() {
  # read <path64> <offset> <max>: bytes of a file starting at offset
  valid_num "$2" "$3"
  f=$(expand "$(b64d "$1")")
  tail -c +"$(($2 + 1))" "$f" 2>/dev/null | head -c "$3"
}

stat_paths() {
  # stat <paths64>: newline separated paths → "mtime\tsize\tpath" for existing files
  { b64d "$1"; echo; } | while IFS= read -r f; do
    [ -n "$f" ] || continue
    g=$(expand "$f")
    [ -f "$g" ] || continue
    printf '%s\t%s\n' "$(fstat "$g")" "$f"
  done
}

media() {
  # media <id> <cwd64> [minutes]: images/pdfs written in the agent's folder since
  # it started (Kuna agents: newer than their meta file; others: last N minutes)
  valid_id "$1"
  [ -z "$3" ] || valid_num "$3"
  ref="$A/$1/meta.json"
  cwd=$(expand "$(b64d "$2")")
  [ -d "$cwd" ] || exit 0
  if [ -n "$3" ]; then set -- -mmin "-$3"; elif [ -f "$ref" ]; then set -- -newer "$ref"; else exit 0; fi
  find "$cwd" -maxdepth 6 \( -name .git -o -name node_modules -o -name .venv -o -name venv -o -name __pycache__ -o -name .cache \) -prune -o \
    -type f \( -iname '*.png' -o -iname '*.jpg' -o -iname '*.jpeg' -o -iname '*.gif' -o -iname '*.webp' -o -iname '*.svg' -o -iname '*.pdf' \) \
    "$@" -print 2>/dev/null | head -n 400 | while IFS= read -r f; do
    printf '%s\t%s\n' "$(fstat "$f")" "$f"
  done
}

cat_file() {
  cat "$(expand "$(b64d "$1")")"
}

ls_dirs() {
  # ls <path64>: subdirectories of a directory (for path completion), without
  # doubled slashes ("proj/" lists "proj/sub", not "proj//sub")
  dir=$(expand "$(b64d "$1")")
  while [ "$dir" != "/" ] && [ "${dir%/}" != "$dir" ]; do dir=${dir%/}; done
  [ "$dir" = "/" ] && dir=""
  for f in "$dir"/* "$dir"/.[!.]*; do
    [ -d "$f" ] && printf '%s\n' "$f"
  done
  return 0
}

real_paths() {
  # realpath <paths64>: newline separated directories -> "path<TAB>physical path"
  # (symlinks resolved, like the working directory an agent reports)
  { b64d "$1"; echo; } | while IFS= read -r f; do
    [ -n "$f" ] || continue
    r=$(cd "$(expand "$f")" 2>/dev/null && pwd -P) && printf '%s\t%s\n' "$f" "$r"
  done
  return 0
}

claude_files() {
  # claude-files <cwds64>: Claude Code config, skills, agents and commands
  c="$HOME/.claude"
  for f in "$c/CLAUDE.md" "$c/settings.json" "$c/settings.local.json" "$c/keybindings.json"; do
    [ -f "$f" ] && printf 'G\t%s\n' "$f"
  done
  for sub in skills agents commands output-styles; do
    # skills: only the SKILL.md entry point, not their reference files
    pat='*.md'
    [ "$sub" = skills ] && pat='SKILL.md'
    [ -d "$c/$sub" ] && find -L "$c/$sub" -maxdepth 5 -type f -name "$pat" 2>/dev/null | head -n 500 | sed 's/^/G	/'
  done
  [ -d "$c/plugins" ] && find -L "$c/plugins" -maxdepth 8 -type f \( -name 'SKILL.md' -o -path '*/agents/*.md' -o -path '*/commands/*.md' \) 2>/dev/null | head -n 500 | sed 's/^/P	/'
  { b64d "$1"; echo; } | while IFS= read -r raw; do
    [ -n "$raw" ] || continue
    w=$(expand "$raw")
    [ -d "$w" ] || continue
    for f in "$w/CLAUDE.md" "$w/CLAUDE.local.md" "$w/AGENTS.md" "$w/.mcp.json" "$w/.claude/settings.json" "$w/.claude/settings.local.json"; do
      [ -f "$f" ] && printf 'L\t%s\n' "$f"
    done
    for sub in skills agents commands; do
      pat='*.md'
      [ "$sub" = skills ] && pat='SKILL.md'
      [ -d "$w/.claude/$sub" ] && find -L "$w/.claude/$sub" -maxdepth 5 -type f -name "$pat" 2>/dev/null | head -n 300 | sed 's/^/L	/'
    done
  done
  return 0
}

